#!/usr/bin/env python3
"""Generate lookup tables for MSXTRACK (note periods, volume scaling, vibrato sine)."""
import math
import sys

PSG_CLOCK = 3579545 / 2  # 1.7897725 MHz on every MSX


def main(out_path, js_path=None):
    lines = ["; Generated by tools/gen_tables.py - do not edit", ""]

    # Note periods: index 0 unused, 1..96 = C-1 .. B-8 (A-4 = 440 Hz)
    periods = [0]
    for k in range(96):
        freq = 440.0 * 2 ** ((k - 45) / 12)
        p = round(PSG_CLOCK / (16 * freq))
        periods.append(min(p, 4095))
    lines.append("notetab:")
    for i in range(0, len(periods), 8):
        lines.append("    dw " + ",".join(str(p) for p in periods[i:i + 8]))
    lines.append("")

    # Volume table: voltab[instrument_vol*16 + channel_vol]
    lines.append("voltab:")
    for iv in range(16):
        row = [round(iv * cv / 15) for cv in range(16)]
        lines.append("    db " + ",".join(str(v) for v in row))
    lines.append("")

    # Vibrato: quarter... full half-period sine, 32 entries 0..255
    sine = [round(255 * math.sin(math.pi * i / 32)) for i in range(32)]
    lines.append("sinetab:")
    lines.append("    db " + ",".join(str(v) for v in sine))
    lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines))

    if js_path:  # the same tables for the web version
        with open(js_path, "w") as f:
            f.write("// Generated by tools/gen_tables.py - do not edit\n")
            f.write("export const notetab = [%s];\n" % ",".join(map(str, periods)))
            vt = [round(iv * cv / 15) for iv in range(16) for cv in range(16)]
            f.write("export const voltab = [%s];\n" % ",".join(map(str, vt)))
            f.write("export const sinetab = [%s];\n" % ",".join(map(str, sine)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
